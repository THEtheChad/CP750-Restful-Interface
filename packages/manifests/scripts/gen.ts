/**
 * Generates `src/generated/` from `firmware/*.json`:
 *   builtin.ts       static JSON imports of every manifest (bundled by `bun build --compile`)
 *   fw_<ver>.ts      per firmware: `ParamName` union and `ParamValues` name -> TS value type map
 *   index.ts         namespaces plus firmware-indexed helper types
 *
 * `bun scripts/gen.ts` writes the files; `bun scripts/gen.ts --check` fails if they are stale.
 */
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { compareFirmware } from "../src/firmware.ts";
import type { Manifest, ValueSchema } from "../src/types.ts";
import { assertManifest } from "../src/validate.ts";

const root = join(import.meta.dir, "..");
const firmwareDir = join(root, "firmware");
const outDir = join(root, "src", "generated");
const HEADER =
  "// Generated by packages/manifests/scripts/gen.ts. Do not edit; run `bun run gen`.\n";

function ident(firmware: string): string {
  return `fw_${firmware.replaceAll(".", "_")}`;
}

function namespace(firmware: string): string {
  return `Fw_${firmware.replaceAll(".", "_")}`;
}

function tsType(schema: ValueSchema): string {
  if (schema.type === "integer") {
    return schema.enum ? schema.enum.map(String).join(" | ") : "number";
  }
  return schema.enum ? schema.enum.map((v) => JSON.stringify(v)).join(" | ") : "string";
}

function docComment(manifest: Manifest, name: string): string {
  const spec = manifest.params[name];
  if (!spec) return "";
  const v = spec.value;
  const range =
    v.type === "integer" && v.minimum !== undefined && v.maximum !== undefined
      ? ` ${v.minimum}..${v.maximum}`
      : "";
  const facts = [
    spec.tier,
    spec.access,
    `${v.type}${range}`,
    spec.unit,
    v.type === "string" ? v["x-format"] : undefined,
    spec.destructive ? "destructive" : undefined,
    spec.internal ? "internal" : undefined,
  ].filter(Boolean);
  const text = [spec.description, `(${facts.join(", ")})`].filter(Boolean).join(" ");
  return `  /** ${text.replaceAll("*/", "*\\/")} */\n`;
}

function firmwareModule(manifest: Manifest): string {
  const names = Object.keys(manifest.params).sort();
  const union = names.map((n) => `\n  | ${JSON.stringify(n)}`).join("");
  const fields = names
    .map((n) => {
      const spec = manifest.params[n];
      return spec
        ? `${docComment(manifest, n)}  ${JSON.stringify(n)}: ${tsType(spec.value)};\n`
        : "";
    })
    .join("");
  return [
    HEADER,
    `export const FIRMWARE = ${JSON.stringify(manifest.firmware)};`,
    `export const STATUS = ${JSON.stringify(manifest.status)};`,
    "",
    `export type ParamName =${union};`,
    "",
    "export interface ParamValues {",
    `${fields}}`,
    "",
  ].join("\n");
}

function builtinModule(manifests: Manifest[]): string {
  const imports = manifests
    .map(
      (m) =>
        `import ${ident(m.firmware)} from "../../firmware/${m.firmware}.json" with { type: "json" };`,
    )
    .join("\n");
  const entries = manifests
    .map((m) => `  ${JSON.stringify(m.firmware)}: ${ident(m.firmware)},`)
    .join("\n");
  return [
    HEADER,
    imports,
    "",
    "/** Raw built-in manifests keyed by firmware. Validate before use (see `builtinManifests`). */",
    "export const BUILTIN_MANIFEST_SOURCES: Readonly<Record<string, unknown>> = {",
    entries,
    "};",
    "",
  ].join("\n");
}

function indexModule(manifests: Manifest[]): string {
  const reexports = manifests
    .map((m) => `export * as ${namespace(m.firmware)} from "./${ident(m.firmware)}.ts";`)
    .join("\n");
  const imports = manifests
    .map((m) => `import type * as ${namespace(m.firmware)} from "./${ident(m.firmware)}.ts";`)
    .join("\n");
  const firmwareList = manifests.map((m) => JSON.stringify(m.firmware));
  const byFirmware = manifests
    .map((m) => `  ${JSON.stringify(m.firmware)}: ${namespace(m.firmware)}.ParamValues;`)
    .join("\n");
  return [
    HEADER,
    imports,
    "",
    reexports,
    "",
    `export const BUILTIN_FIRMWARE = [${firmwareList.join(", ")}] as const;`,
    "",
    "export type BuiltinFirmware = (typeof BUILTIN_FIRMWARE)[number];",
    "",
    "/** Param name -> TS value type, per built-in firmware. */",
    "export interface ParamValuesByFirmware {",
    byFirmware,
    "}",
    "",
    "export type ParamNameOf<F extends BuiltinFirmware> = keyof ParamValuesByFirmware[F] & string;",
    "",
    "export type ParamValueOf<",
    "  F extends BuiltinFirmware,",
    "  N extends ParamNameOf<F>,",
    "> = ParamValuesByFirmware[F][N];",
    "",
  ].join("\n");
}

async function loadFirmwareManifests(): Promise<Manifest[]> {
  const files = (await readdir(firmwareDir)).filter((f) => f.endsWith(".json"));
  const manifests = await Promise.all(
    files.map(async (file) => {
      const manifest = assertManifest(
        JSON.parse(await readFile(join(firmwareDir, file), "utf8")),
        file,
      );
      if (file !== `${manifest.firmware}.json`) {
        throw new Error(`${file}: file must be named ${manifest.firmware}.json`);
      }
      return manifest;
    }),
  );
  return manifests.sort((a, b) => compareFirmware(a.firmware, b.firmware));
}

async function main(): Promise<number> {
  const check = process.argv.includes("--check");
  const manifests = await loadFirmwareManifests();
  const files = new Map<string, string>([
    ["builtin.ts", builtinModule(manifests)],
    ["index.ts", indexModule(manifests)],
  ]);
  for (const m of manifests) files.set(`${ident(m.firmware)}.ts`, firmwareModule(m));

  await mkdir(outDir, { recursive: true });
  const existing = new Set((await readdir(outDir)).filter((f) => f.endsWith(".ts")));
  const stale: string[] = [];
  for (const [file, content] of files) {
    const current = existing.has(file) ? await readFile(join(outDir, file), "utf8") : null;
    if (current === content) continue;
    if (check) stale.push(file);
    else await writeFile(join(outDir, file), content);
  }
  for (const file of existing) {
    if (files.has(file)) continue;
    if (check) stale.push(file);
    else await rm(join(outDir, file));
  }

  if (check && stale.length) {
    console.error(`src/generated is stale (${stale.join(", ")}). Run \`bun run gen\`.`);
    return 1;
  }
  console.log(
    check ? "src/generated is up to date." : `Wrote ${files.size} files to src/generated.`,
  );
  return 0;
}

process.exit(await main());
