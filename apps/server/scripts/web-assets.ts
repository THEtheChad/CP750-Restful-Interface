/**
 * Generates `src/generated/web-assets.ts` from a Vite build (default `apps/web/dist`): one
 * `import … with { type: "file" }` per file plus a URL-path map. Under `bun build --compile`
 * those imports embed the files in the executable and resolve to `/$bunfs/…` paths that
 * `Bun.file` reads; from source they resolve to the files on disk.
 *
 *   bun apps/server/scripts/web-assets.ts            from apps/web/dist (empty map if missing)
 *   bun apps/server/scripts/web-assets.ts --empty    reset to the committed empty map
 *   bun apps/server/scripts/web-assets.ts --dist <d> from another directory
 */
import { readdir, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { parseArgs } from "node:util";

const serverDir = join(import.meta.dir, "..");
export const WEB_ASSETS_MODULE = join(serverDir, "src", "generated", "web-assets.ts");
export const DEFAULT_WEB_DIST = join(serverDir, "..", "web", "dist");

const HEADER =
  "// Generated by apps/server/scripts/web-assets.ts. Do not edit; run `bun apps/server/scripts/web-assets.ts`.\n";

async function listFiles(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await listFiles(path)));
    else if (entry.isFile()) out.push(path);
  }
  return out;
}

function toPosix(path: string): string {
  return path.split(sep).join("/");
}

/** The module source for the files in `distDir` (or an empty map when `distDir` is null). */
export async function webAssetsModule(
  distDir: string | null,
  moduleFile = WEB_ASSETS_MODULE,
): Promise<string> {
  const files = distDir ? (await listFiles(distDir)).sort() : [];
  const lines = [HEADER];
  if (files.length === 0) {
    lines.push(
      "// Empty: no web build was embedded. `bun run compile` fills this in temporarily.",
      "",
      'import type { WebAssets } from "../web.ts";',
      "",
      "/** URL path -> embedded file path. */",
      "export const WEB_ASSETS: WebAssets = {};",
      "",
    );
    return lines.join("\n");
  }
  // Non-TS assets (and `.html`, which Bun would otherwise bundle) are imported as files; the
  // type checker cannot model that, so this generated file opts out.
  lines.splice(0, 0, "// @ts-nocheck");
  const imports: string[] = [];
  const entries: string[] = [];
  files.forEach((file, i) => {
    let spec = toPosix(relative(dirname(moduleFile), file));
    if (!spec.startsWith(".")) spec = `./${spec}`;
    imports.push(`import asset${i} from ${JSON.stringify(spec)} with { type: "file" };`);
    entries.push(
      `  ${JSON.stringify(`/${toPosix(relative(distDir as string, file))}`)}: asset${i},`,
    );
  });
  lines.push(
    'import type { WebAssets } from "../web.ts";',
    ...imports,
    "",
    "/** URL path -> embedded file path. */",
    "export const WEB_ASSETS: WebAssets = {",
    ...entries,
    "};",
    "",
  );
  return lines.join("\n");
}

async function isDir(path: string): Promise<boolean> {
  return stat(path).then(
    (s) => s.isDirectory(),
    () => false,
  );
}

/** Writes the module; returns the number of embedded files. */
export async function writeWebAssetsModule(distDir: string | null): Promise<number> {
  const dir = distDir && (await isDir(distDir)) ? distDir : null;
  const source = await webAssetsModule(dir);
  await writeFile(WEB_ASSETS_MODULE, source);
  return dir ? (await listFiles(dir)).length : 0;
}

if (import.meta.main) {
  const { values } = parseArgs({
    options: { empty: { type: "boolean" }, dist: { type: "string" } },
    strict: true,
  });
  const count = await writeWebAssetsModule(values.empty ? null : (values.dist ?? DEFAULT_WEB_DIST));
  console.log(`Wrote ${relative(process.cwd(), WEB_ASSETS_MODULE)} (${count} files).`);
}
