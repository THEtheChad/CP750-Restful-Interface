/**
 * Generates `src/api/generated/schema.ts` from the committed OpenAPI document
 * (`openapi/cp750.openapi.json`) with openapi-typescript.
 *
 *   bun scripts/gen-api.ts           write the file
 *   bun scripts/gen-api.ts --check   exit 1 if the committed file is stale (CI)
 */
import { readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { parseArgs } from "node:util";
import openapiTS, { astToString } from "openapi-typescript";

const webDir = join(import.meta.dir, "..");
const specPath = join(webDir, "..", "..", "openapi", "cp750.openapi.json");
const outPath = join(webDir, "src", "api", "generated", "schema.ts");

const HEADER =
  "// Generated by apps/web/scripts/gen-api.ts from openapi/cp750.openapi.json. Do not edit;\n" +
  "// run `bun run gen`.\n\n";

const { values } = parseArgs({ options: { check: { type: "boolean" } }, strict: true });

const spec = JSON.parse(await readFile(specPath, "utf8"));
const ast = await openapiTS(spec, { alphabetize: true });
const source = HEADER + astToString(ast);
const shown = relative(process.cwd(), outPath);

if (values.check) {
  const current = await readFile(outPath, "utf8").catch(() => "");
  if (current !== source) {
    console.error(`${shown} is stale; run \`bun run gen\`.`);
    process.exit(1);
  }
  console.log(`${shown} is up to date.`);
} else {
  await writeFile(outPath, source);
  console.log(`Wrote ${shown}.`);
}
